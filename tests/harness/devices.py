_KEBAB = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


class DeviceStartError(RuntimeError):
    """A Device did not come up, or did not start publishing, in time."""


def _run(args: Sequence[str], *, env: dict[str, str] | None = None, check: bool = True,
         timeout: float = 120) -> subprocess.CompletedProcess[str]:
    result = subprocess.run(list(args), env=env, capture_output=True, text=True, timeout=timeout)
    if check and result.returncode != 0:
        raise RuntimeError(
            f"command failed ({result.returncode}): {' '.join(args)}\n"
            f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
        )
    return result


def _read_env_file(path: Path) -> dict[str, str]:
    values = {}
    for line in path.read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            key, _, value = line.partition("=")
            values[key.strip()] = value.strip()
    return values


@dataclass
class Device:
    """One running Device from the Device Kit, as seen from a test.

    Two ways to address it:

    - from the host (pytest itself): ``host_api_url``, ``host_rtsps_port``;
    - from another container on the session network: ``address`` (the label),
      ``network_api_url``, ``rtsps_url()``.
    """

    label: str
    variant: str
    cameras: tuple[str, ...]
    username: str
    password: str
    workdir: Path
    project: str
    _harness: DeviceHarness = field(repr=False)
    gps: bool = False
    gps_tracks: Path = GPS_TRACKS
    _ports: dict[int, int] = field(default_factory=dict, repr=False)

    # -- identity ---------------------------------------------------------

    @property
    def address(self) -> str:
        """DNS name of the Device on the session network."""
        return self.label

    @property
    def credentials(self) -> tuple[str, str]:
        return (self.username, self.password)

    @property
    def cert_path(self) -> Path:
        return self.workdir / "certs" / "server.crt"

    @property
    def fingerprint(self) -> str:
        """SHA-256 of the Device's current certificate, in MediaMTX
        ``sourceFingerprint`` form (lowercase hex, no colons)."""
        der = ssl.PEM_cert_to_DER_cert(self.cert_path.read_text())
        return hashlib.sha256(der).hexdigest()

    # -- addresses ----------------------------------------------------------

    @property
    def host_api_port(self) -> int:
        return self._host_port(API_PORT)

    @property
    def host_rtsps_port(self) -> int:
        return self._host_port(RTSPS_PORT)

    @property
    def host_api_url(self) -> str:
        return f"https://127.0.0.1:{self.host_api_port}"

    @property
    def network_api_url(self) -> str:
        return f"https://{self.address}:{API_PORT}"

    def rtsps_url(self, camera: str | None = None, *, credentials: bool = True,
                  scheme: str = "rtsps", port: int = RTSPS_PORT) -> str:
        """URL of a Camera as another container on the session network sees it.

        ``scheme`` and ``port`` exist so tests can try what must be refused,
        such as plain ``rtsp`` on 8554.
        """
        camera = camera or self.cameras[0]
        auth = f"{self.username}:{self.password}@" if credentials else ""
        return f"{scheme}://{auth}{self.address}:{port}/{camera}"

    def api_client(self, *, auth: bool = True, **kwargs) -> httpx.Client:
        """An httpx client for the Device API from the host, trusting exactly
        this Device's certificate."""
        context = ssl.create_default_context(cafile=str(self.cert_path))
        return httpx.Client(
            base_url=self.host_api_url,
            auth=self.credentials if auth else None,
            verify=context,
            timeout=kwargs.pop("timeout", 10),
            **kwargs,
        )

    # -- the GPS Sidecar (a Device started with gps=True) ---------------------

    @property
    def host_gps_port(self) -> int:
        """The Sidecar's 9998, published on the Device's container (device-gps.yaml)."""
        return self._host_port(GPS_PORT)

    @property
    def host_gps_url(self) -> str:
        return f"https://127.0.0.1:{self.host_gps_port}"

    def gps_client(self, *, auth: bool = True, **kwargs) -> httpx.Client:
        """An httpx client for the GPS Sidecar from the host, trusting exactly
        this Device's certificate."""
        context = ssl.create_default_context(cafile=str(self.cert_path))
        return httpx.Client(
            base_url=self.host_gps_url,
            auth=self.credentials if auth else None,
            verify=context,
            timeout=kwargs.pop("timeout", 10),
            **kwargs,
        )

    def gps_state(self) -> dict:
        """The Sidecar container's ``docker compose ps`` entry: ``State``
        (running, exited...) and ``ExitCode``."""
        out = self._compose("ps", "-a", "--format", "json", GPS_SERVICE).stdout.strip()
        entries = [json.loads(line) for line in out.splitlines() if line.strip()]
        if not entries:
            raise RuntimeError(f"Device {self.label!r} has no GPS Sidecar container")
        return entries[0]

    def gps_logs(self) -> str:
        return self._compose("logs", "--no-color", GPS_SERVICE, check=False).stdout

    def stop_gps(self) -> None:
        """Stop the Sidecar alone, as a receiver's service dying would; MediaMTX keeps running."""
        self._compose("stop", "-t", "2", GPS_SERVICE)

    def start_gps(self, *, wait: bool = True) -> None:
        """Start the Sidecar again (or for the first time, after ``stop_gps``)."""
        self._compose("start", GPS_SERVICE)
        if wait:
            self.wait_gps()

    def wait_gps(self, timeout: float = 60) -> None:
        """Block until the Sidecar completes a TLS handshake on its port."""
        deadline = time.monotonic() + timeout
        last_error = "never reached the Sidecar"
        while time.monotonic() < deadline:
            try:
                with self.gps_client(timeout=3) as client:
                    client.get("/")
                return
            except (httpx.HTTPError, ssl.SSLError, RuntimeError) as exc:
                self._ports.clear()
                last_error = repr(exc)
            time.sleep(0.5)
        raise DeviceStartError(
            f"GPS Sidecar of {self.label!r} not ready after {timeout}s: {last_error}\n{self.gps_logs()}"
        )

    # -- lifecycle ------------------------------------------------------------

    def stop(self) -> None:
        self._compose("stop", "-t", "2")
        self._ports.clear()

    def start(self, *, wait: bool = True) -> None:
        self._compose("start")
        self._ports.clear()
        if wait:
            self.wait_ready()

    def restart(self, *, wait: bool = True) -> None:
        self._compose("restart", "-t", "2")
        self._ports.clear()
        if wait:
            self.wait_ready()

    def pause(self) -> None:
        """Freeze the Device: its sockets stay open but nothing answers."""
        self._compose("pause")

    def unpause(self) -> None:
        self._compose("unpause")

    def throttle(self, *, kbit: int | None = None, delay_ms: int = 0, loss_percent: float = 0) -> None:
        """Shape everything the Device sends, as a slow or lossy uplink would:
        ``kbit`` caps the rate (``tc tbf``), ``delay_ms`` and ``loss_percent``
        go to ``netem``. Replaces any earlier throttle. A restart clears it,
        since the shaping lives in the container's network namespace.

        The Device's Relay pull runs over TCP, so a rate cap below the Feed's
        bitrate fills the Device's per-reader write queue until MediaMTX
        discards packets (working notes, Gotchas)."""
        if kbit is None and not delay_ms and not loss_percent:
            raise ValueError("throttle needs kbit, delay_ms or loss_percent; use unthrottle() to clear")
        netem = f"netem delay {int(delay_ms)}ms loss {float(loss_percent)}% limit 10000"
        if kbit is not None:
            burst = max(int(kbit) * 1000 // 8 // 20, 4000)  # 50 ms of the rate, at least a few MTUs
            tbf = f"tbf rate {int(kbit)}kbit burst {burst} latency 400ms"
        if kbit is None:
            add = f'tc qdisc add dev "$dev" root {netem}'
        elif not delay_ms and not loss_percent:
            add = f'tc qdisc add dev "$dev" root {tbf}'
        else:
            add = (f'tc qdisc add dev "$dev" root handle 1: {netem} && '
                   f'tc qdisc add dev "$dev" parent 1:1 handle 10: {tbf}')
        self._harness._tc(self, f'{_EACH_UPLINK}tc qdisc del dev "$dev" root 2>/dev/null; {add} || exit 1; done')

    def unthrottle(self) -> None:
        """Remove any throttle; harmless on a Device that has none."""
        self._harness._tc(self, f'{_EACH_UPLINK}tc qdisc del dev "$dev" root 2>/dev/null; done; true')

    def regenerate_cert(self, *, restart: bool = True) -> str:
        """Give the Device a new certificate, as a weekly rebuild would.
        Returns the new fingerprint."""
        self._harness._gen_cert(self.workdir, self.label, force=True)
        if restart:
            self.restart()
        return self.fingerprint

    def exec(self, *cmd: str, check: bool = True) -> subprocess.CompletedProcess[str]:
        """Run a command inside the Device's MediaMTX container."""
        return self._compose("exec", "-T", SERVICE, *cmd, check=check)

    def logs(self) -> str:
        return self._compose("logs", "--no-color", check=False).stdout

    def wait_ready(self, timeout: float = 60, *, publishing: bool = True) -> None:
        """Block until the API answers and, unless ``publishing`` is False,
        every Camera is publishing."""
        deadline = time.monotonic() + timeout
        last_error = "never reached the API"
        while time.monotonic() < deadline:
            try:
                with self.api_client(timeout=3) as api:
                    if not publishing:
                        if api.get("/v3/paths/list").status_code == 200:
                            return
                        last_error = "API up, not answering /v3/paths/list yet"
                    elif all(self._camera_ready(api, camera) for camera in self.cameras):
                        return
                    last_error = "API up, Cameras not yet publishing"
            except (httpx.HTTPError, ssl.SSLError, RuntimeError) as exc:
                self._ports.clear()
                last_error = repr(exc)
            time.sleep(0.5)
        raise DeviceStartError(
            f"Device {self.label!r} not ready after {timeout}s: {last_error}\n{self.logs()}"
        )

    @staticmethod
    def _camera_ready(api: httpx.Client, camera: str) -> bool:
        response = api.get(f"/v3/paths/get/{camera}")
        if response.status_code != 200:
            return False
        body = response.json()
        return bool(body.get("available", body.get("ready")))

    # -- internals ------------------------------------------------------------

    def _host_port(self, container_port: int) -> int:
        if container_port not in self._ports:
            out = self._compose("port", SERVICE, str(container_port)).stdout.strip()
            # "127.0.0.1:55012"; take the last line in case of IPv4 + IPv6.
            self._ports[container_port] = int(out.splitlines()[-1].rsplit(":", 1)[1])
        return self._ports[container_port]

    def _compose(self, *args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
        return self._harness._compose(self, *args, check=check)


@dataclass
class ScriptedDevice:
    """A fake Device whose API answers what the test scripted (see
    ``scripted_device_api.py``). For proving the instance treats a Device as
    untrusted input, and for driving Quality's config writes without a
    camera. It has a real kit certificate and credentials, but no media:
    nothing can play from it.

    Started with ``sidecar_lines``, it also runs a hostile GPS Sidecar on 9998
    that streams those lines, byte for byte, over and over; with
    ``sidecar_impostor`` that Sidecar presents another certificate for the
    same label, as someone impersonating the Device's Sidecar would."""

    label: str
    container: str
    username: str
    password: str
    workdir: Path
    host_api_port: int = 0
    host_gps_port: int = 0
    impostor: bool = False

    @property
    def address(self) -> str:
        return self.label

    @property
    def credentials(self) -> tuple[str, str]:
        return (self.username, self.password)

    @property
    def cert_path(self) -> Path:
        return self.workdir / "certs" / "server.crt"

    @property
    def fingerprint(self) -> str:
        der = ssl.PEM_cert_to_DER_cert(self.cert_path.read_text())
        return hashlib.sha256(der).hexdigest()

    @property
    def host_api_url(self) -> str:
        return f"https://127.0.0.1:{self.host_api_port}"

    def api_client(self, **kwargs) -> httpx.Client:
        """An httpx client for the fake's API from the host, as another
        client of the Device would hold one (a second instance, say)."""
        context = ssl.create_default_context(cafile=str(self.cert_path))
        return httpx.Client(base_url=self.host_api_url, auth=self.credentials, verify=context,
                            timeout=kwargs.pop("timeout", 10), **kwargs)

    def patches(self) -> list[dict]:
        """Every ``PATCH /v3/config/paths/patch/{name}`` the fake received, in
        order, as ``{"path": name, "body": {...}}``, whatever it answered."""
        with self.api_client() as api:
            return api.get("/_script/patches").raise_for_status().json()

    def config_reads(self) -> list[str]:
        """The path name of every ``GET /v3/config/paths/get/{name}`` the fake
        answered, in order."""
        with self.api_client() as api:
            return api.get("/_script/config-reads").raise_for_status().json()

    def restart(self, *, started: str | None = None) -> None:
        """Act out a Device restart: every path config goes back to what was
        scripted, since API changes live only in a Device's memory, and
        ``/v3/info`` reports a new ``started`` (now, unless given)."""
        self._control("/_script/restart", {"started": started})

    def fail_patches(self, status: int | None, body: dict | None = None) -> None:
        """Answer every PATCH with ``status`` and ``body`` and change nothing,
        until called with ``None``. Still recorded in ``patches()``."""
        self._control("/_script/fail-patches", {"status": status, "body": body})

    def _control(self, path: str, body: dict) -> None:
        with self.api_client() as api:
            api.post(path, json=body).raise_for_status()

    # -- the scripted GPS Sidecar (started with sidecar_lines) --------------------

    @property
    def sidecar_cert_path(self) -> Path:
        """The certificate the Sidecar presents: the Device's own, or the impostor's."""
        return self.workdir / "impostor" / "certs" / "server.crt" if self.impostor else self.cert_path

    @property
    def sidecar_fingerprint(self) -> str:
        der = ssl.PEM_cert_to_DER_cert(self.sidecar_cert_path.read_text())
        return hashlib.sha256(der).hexdigest()

    def gps_client(self, **kwargs) -> httpx.Client:
        """An httpx client for the Sidecar from the host, with the Device's credentials,
        trusting exactly the Device's certificate (so an impostor's handshake fails)."""
        context = ssl.create_default_context(cafile=str(self.cert_path))
        return httpx.Client(base_url=f"https://127.0.0.1:{self.host_gps_port}", auth=self.credentials,
                            verify=context, timeout=kwargs.pop("timeout", 10), **kwargs)

    def sidecar_requests(self) -> list[dict]:
        """Every request the Sidecar read, in order, as ``{"path", "authorization"}``. A client
        that refused its certificate never got as far as sending one."""
        return self._sidecar()["requests"]

    def sidecar_connections(self) -> int:
        """How many connections the Sidecar accepted, counted before the TLS handshake."""
        return self._sidecar()["connections"]

    def _sidecar(self) -> dict:
        with self.api_client() as api:
            return api.get("/_script/sidecar").raise_for_status().json()

    def set_clock_offset(self, seconds: int) -> None:
        """Set the Device's clock this many seconds off the host's (negative is behind).
        The Device reads it per request, so it takes effect at once."""
        (self.workdir / "clock-offset").write_text(str(int(seconds)))


class DeviceHarness:
    """One test session's worth of Devices on the shared Docker host."""

    def __init__(self, workdir: Path, session_id: str | None = None):
        self.session_id = session_id or f"cvt-{secrets.token_hex(4)}"
        self.network = f"{self.session_id}-net"
        self.workdir = Path(workdir)
        self.devices: dict[str, Device] = {}
        self.scripted: dict[str, ScriptedDevice] = {}
        self._tc_image: str | None = None
        self._open = False

    # -- session ---------------------------------------------------------------

    def open(self) -> DeviceHarness:
        if not self._open:
            _run(["docker", "network", "create", "--label", f"{SESSION_LABEL}={self.session_id}",
                  self.network])
            self._open = True
            atexit.register(self.close)
        return self

    def close(self) -> None:
        """Remove every Device and the session network. Safe to call twice."""
        if not self._open:
            return
        errors = []
        for device in list(self.devices.values()):
            try:
                self.remove_device(device)
            except Exception as exc:  # keep tearing down the rest
                errors.append(exc)
        for scripted in list(self.scripted.values()):
            try:
                self.remove_scripted_device(scripted)
            except Exception as exc:
                errors.append(exc)
        result = _run(["docker", "network", "rm", self.network], check=False)
        if result.returncode != 0 and "not found" not in result.stderr:
            errors.append(RuntimeError(result.stderr))
        if self._tc_image:
            _run(["docker", "image", "rm", "-f", self._tc_image], check=False)
            self._tc_image = None
        self._open = False
        atexit.unregister(self.close)
        if errors:
            raise RuntimeError(f"harness teardown left debris: {errors}")

    def __enter__(self) -> DeviceHarness:
        return self.open()

    def __exit__(self, *exc_info) -> None:
        self.close()

    # -- Devices --------------------------------------------------------------

    def add_device(self, label: str, *, variant: str = "test-pattern", wait: bool = True,
                   camera: str | None = None, settings: dict[str, str] | None = None,
                   gps: bool = False, gps_tracks: Path | None = None) -> Device:
        """Generate a certificate and credentials with the kit's generator,
        then start the variant's compose stack on the session network.

        ``camera`` is the host device a camera variant captures from (passed
        to ``gen-cert.sh --camera``). With no webcam, ``/dev/null`` brings the
        kit up with a capture that fails and retries; its Camera never becomes
        available, so pass ``wait=False``.

        ``settings`` are extra lines for the Device's ``.env``, added after
        ``gen-cert.sh`` writes it, as a student would (``CAMERA_HFLIP``).

        ``gps`` starts the kit with ``--profile gps``, so the GPS Sidecar runs
        beside MediaMTX; pass ``settings={"GPS_SOURCE": "replay:<file>"}`` to
        replay a track. ``gps_tracks`` is the folder it replays from, the
        kit's own ``device-kit/gps/tracks`` unless a test wrote its own. With
        ``wait``, the Sidecar is waited for too."""
        if not self._open:
            self.open()
        if not _KEBAB.match(label):
            raise ValueError(f"Device label must be kebab-case: {label!r}")
        if label in self.devices:
            raise ValueError(f"Device {label!r} already exists in this session")
        if variant not in VARIANT_CAMERAS:
            raise ValueError(f"unknown Device Kit variant {variant!r}")

        workdir = self.workdir / label
        workdir.mkdir(parents=True, exist_ok=True)
        self._gen_cert(workdir, label, camera=camera)
        if settings:
            with (workdir / ".env").open("a") as env_file:
                env_file.writelines(f"{key}={value}\n" for key, value in settings.items())
        env = _read_env_file(workdir / ".env")
        device = Device(
            label=label,
            variant=variant,
            cameras=VARIANT_CAMERAS[variant],
            username=env["INSTANCE_USER"],
            password=env["INSTANCE_PASS"],
            workdir=workdir,
            project=f"{self.session_id}-{label}",
            _harness=self,
            gps=gps,
            gps_tracks=Path(gps_tracks) if gps_tracks else GPS_TRACKS,
        )
        self.devices[label] = device
        self._compose(device, "up", "-d", "--quiet-pull")
        if wait:
            device.wait_ready()
            if gps:
                device.wait_gps()
        return device

    def remove_device(self, device: Device) -> None:
        self._compose(device, "down", "-v", "--remove-orphans", "-t", "2")
        self.devices.pop(device.label, None)

    def add_scripted_device(self, label: str, image: str, *, paths: list[dict],
                            global_config: dict | None = None, path_configs: dict[str, dict] | None = None,
                            started: str | None = None, clock_offset: int = 0,
                            sidecar_lines: list[bytes] | None = None, sidecar_impostor: bool = False,
                            timeout: float = 30) -> ScriptedDevice:
        """Start a fake Device API on the session network under ``label``,
        answering ``/v3/paths/list`` with ``paths``, each path's config from
        ``path_configs`` (name to ``/v3/config/paths/get`` body), and
        ``/v3/info`` ``started`` from ``started`` (default: when it started),
        its clock ``clock_offset`` seconds off the host's. ``image`` must have
        Python 3.11 or later (the instance image does).

        ``sidecar_lines`` adds a hostile GPS Sidecar on 9998 streaming those
        lines (each without its newline) round after round, presenting the
        Device's certificate, or with ``sidecar_impostor`` one of its own."""
        if not self._open:
            self.open()
        if label in self.devices or label in self.scripted:
            raise ValueError(f"Device {label!r} already exists in this session")
        workdir = self.workdir / label
        workdir.mkdir(parents=True, exist_ok=True)
        self._gen_cert(workdir, label)
        env = _read_env_file(workdir / ".env")
        shutil.copy(SCRIPTED_API, workdir / "api.py")
        script = {"paths": paths}
        if global_config is not None:
            script["global"] = global_config
        if path_configs is not None:
            script["path_configs"] = path_configs
        if started is not None:
            script["started"] = started
        if sidecar_lines is not None:
            certs = "/srv/certs"
            if sidecar_impostor:  # the same label, a key and certificate of its own
                (workdir / "impostor").mkdir(exist_ok=True)
                self._gen_cert(workdir / "impostor", label)
                certs = "/srv/impostor/certs"
            script["sidecar"] = {"lines": [base64.b64encode(line).decode() for line in sidecar_lines],
                                 "cert": f"{certs}/server.crt", "key": f"{certs}/server.key"}
        (workdir / "script.json").write_text(json.dumps(script))
        (workdir / "clock-offset").write_text(str(int(clock_offset)))
        container = f"{self.session_id}-{label}"
        gps_port = ("-p", f"127.0.0.1::{GPS_PORT}") if sidecar_lines is not None else ()
        _run(["docker", "run", "-d", "--name", container, "--network", self.network,
              "--network-alias", label, "--label", f"{SESSION_LABEL}={self.session_id}",
              "-p", "127.0.0.1::9997", *gps_port, "-v", f"{workdir}:/srv:ro", "--entrypoint", "python",
              image, "/srv/api.py", "/srv/certs/server.crt", "/srv/certs/server.key", "/srv/script.json"])

        def host_port(container_port: int) -> int:
            out = _run(["docker", "port", container, f"{container_port}/tcp"]).stdout
            return int(out.splitlines()[-1].rsplit(":", 1)[1])

        device = ScriptedDevice(label=label, container=container, username=env["INSTANCE_USER"],
                                password=env["INSTANCE_PASS"], workdir=workdir, host_api_port=host_port(API_PORT),
                                host_gps_port=host_port(GPS_PORT) if gps_port else 0, impostor=sidecar_impostor)
        self.scripted[label] = device
        deadline = time.monotonic() + timeout
        while True:
            try:
                httpx.get(f"{device.host_api_url}/v3/info", verify=False, timeout=2).raise_for_status()
                return device
            except httpx.HTTPError as exc:
                if time.monotonic() > deadline:
                    logs = _run(["docker", "logs", container], check=False)
                    raise DeviceStartError(f"scripted Device {label!r} never answered: {exc!r}\n"
                                           f"{logs.stdout}{logs.stderr}") from exc
                time.sleep(0.3)

    def remove_scripted_device(self, device: ScriptedDevice) -> None:
        _run(["docker", "rm", "-f", device.container], check=False)
        self.scripted.pop(device.label, None)

    # -- probing from inside the session network -------------------------------

    def run_in_network(self, image: str, *args: str, entrypoint: str | None = None,
                       timeout: float = 60) -> subprocess.CompletedProcess[str]:
        """Run a throwaway container on the session network."""
        cmd = ["docker", "run", "--rm", "--network", self.network,
               "--label", f"{SESSION_LABEL}={self.session_id}"]
        if entrypoint:
            cmd += ["--entrypoint", entrypoint]
        return _run([*cmd, image, *args], check=False, timeout=timeout)

    def probe(self, *ffprobe_args: str, timeout: float = 60) -> subprocess.CompletedProcess[str]:
        """Run ffprobe from a container on the session network."""
        return self.run_in_network(PROBE_IMAGE, *ffprobe_args, entrypoint="ffprobe",
                                   timeout=timeout)

    # -- internals ------------------------------------------------------------

    def _tc(self, device: Device, script: str) -> None:
        """Run a shell ``script`` with ``tc`` in a throwaway sidecar that joins
        the Device's network namespace. Only the sidecar gets ``NET_ADMIN``;
        the Device container runs exactly as the kit's compose file says."""
        if self._tc_image is None:
            tag = f"{self.session_id}-tc"
            build = subprocess.run(["docker", "build", "-q", "-t", tag, "--label", f"{SESSION_LABEL}={self.session_id}",
                                    "-"], input=TC_DOCKERFILE, capture_output=True, text=True, timeout=300)
            if build.returncode != 0:
                raise RuntimeError(f"could not build the tc sidecar image:\n{build.stderr}")
            self._tc_image = tag
        container = device._compose("ps", "-q", SERVICE).stdout.strip()
        if not container:
            raise RuntimeError(f"Device {device.label!r} is not running, so it cannot be throttled")
        _run(["docker", "run", "--rm", "--network", f"container:{container}", "--cap-add", "NET_ADMIN",
              "--label", f"{SESSION_LABEL}={self.session_id}", "--entrypoint", "/bin/sh", self._tc_image,
              "-c", script], timeout=60)

    def _gen_cert(self, workdir: Path, label: str, *, force: bool = False,
                  camera: str | None = None) -> None:
        args = [shutil.which("bash") or "bash", str(GEN_CERT),
                "-o", str(workdir / "certs"), "-e", str(workdir / ".env"), "-s", label]
        if force:
            args.append("--force")
        if camera:
            args += ["--camera", camera]
        _run([*args, str(workdir)], env={**os.environ, "NO_COLOR": "1"})

    def _compose(self, device: Device, *args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
        env = {
            **os.environ,
            "CV_TEST_SESSION": self.session_id,
            "CV_TEST_NETWORK": self.network,
            "CV_DEVICE_ALIAS": device.label,
            "DEVICE_CERTS_DIR": str(device.workdir / "certs"),
            "CV_GPS_TRACKS": str(device.gps_tracks),
        }
        kit, *stand_in = STAND_INS.get(device.variant, (device.variant,))
        overlays = (*stand_in, OVERRIDE, *((GPS_OVERRIDE,) if device.gps else ()))
        cmd = [
            "docker", "compose",
            "-p", device.project,
            *(("--profile", "gps") if device.gps else ()),
            "--env-file", str(device.workdir / ".env"),
            "-f", str(KIT_DIR / kit / "compose.yaml"),
            *[arg for overlay in overlays for arg in ("-f", str(overlay))],
            *args,
        ]
        return _run(cmd, env=env, check=check, timeout=180)
