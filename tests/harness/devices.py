"""Bring Device Kit Devices up and down for a test session.

Every DeviceHarness is one isolated session on the shared Docker host:

- its own Docker network, ``cvt-<session>-net``; every Device joins it under
  its label as a DNS alias, so other containers (the Relay, a probe) reach a
  Device at ``<label>:8322`` and ``<label>:9997``;
- one compose project per Device, ``cvt-<session>-<label>``;
- no fixed host ports: each Device's RTSPS and API ports are published on
  ephemeral 127.0.0.1 ports, looked up after every (re)start;
- certificates and credentials generated by the kit's own ``gen-cert.sh``
  into the session's temp directory, never into the repo.

Close the harness (or use it as a context manager) to remove every container
and the network.
"""

