"""Relay Controller: the only component that talks to the Relay's API.

The backend owns the Relay's whole path configuration (ADR 0001). Callers
declare the desired path set; a background loop reconciles it onto the Relay
and keeps doing so, so a Relay that restarted (and so forgot every path set
through its API) gets everything back within one interval without anyone
noticing the restart.

Only the backend may use the Relay: its API, WHEP and RTSP servers listen on
loopback, which under Linux host networking is the whole host's, so each
also requires the internal user the supervisor generates at every start
(``RelayCredentials``). The controller, the Playback Gateway and the hold
paths authenticate as it; browsers never see it.

Reconciling compares path *names* against the Relay, and path *configs*
against what this controller last applied, never against what the Relay
reports: the Relay redacts credentials in what it returns, so comparing its
answer would look like drift on every pass.
"""

from __future__ import annotations

import asyncio
import logging
from collections.abc import Iterable
from dataclasses import dataclass, field
from typing import Any
from urllib.parse import quote, urlsplit, urlunsplit

import httpx

from camera_viewer.device_client import same_host
from camera_viewer.registry import Device

log = logging.getLogger("camera_viewer.relay")


@dataclass(frozen=True)
class RelayCredentials:
    """The Relay's internal user, generated by the supervisor at every start
    (``CV_RELAY_USER`` / ``CV_RELAY_PASS``). Empty when the Relay runs without
    one (development outside the image)."""

    user: str = ""
    password: str = field(default="", repr=False)

    def httpx_auth(self) -> tuple[str, str] | None:
        return (self.user, self.password) if self.user else None


@dataclass(frozen=True)
class RecordSettings:
    """How the Relay records any path. Every Camera path carries the same
    settings whether or not it is recording, so switching ``record`` on or
    off is a hot reload that never drops a reader; a change to anything else
    on a path would recreate it."""

    path: str                    # recordPath template; must contain %path and the time
    on_segment_create: str       # command the Relay runs when it opens a segment file
    on_segment_complete: str     # command the Relay runs when it finalizes one
    # One uninterrupted Recording is one file for up to this long (the Relay allows at most 24h).
    segment_duration: str = "24h"

    def config(self) -> dict[str, Any]:
        return {
            "recordPath": self.path,
            "recordFormat": "fmp4",
            "recordSegmentDuration": self.segment_duration,
            "recordDeleteAfter": "0s",  # the Capture Store owns the files, never the Relay
            "runOnRecordSegmentCreate": self.on_segment_create,
            "runOnRecordSegmentComplete": self.on_segment_complete,
        }


@dataclass(frozen=True)
class RelayPath:
    """What the Relay should do for one path."""

    source: str                  # URL the Relay pulls from, credentials included
    fingerprint: str | None      # pinned certificate of an rtsps:// source
    on_demand: bool = True       # pull only while someone reads the path
    record: bool = False         # write the Feed to disk
    recording: RecordSettings | None = None

    def config(self) -> dict[str, Any]:
        config: dict[str, Any] = {
            "source": self.source,
            "sourceOnDemand": self.on_demand,
            "rtspTransport": "tcp",
        }
        if self.fingerprint:
            config["sourceFingerprint"] = self.fingerprint
        if self.recording:
            config |= self.recording.config()
            config["record"] = self.record
        return config


def quote_path(name: str) -> str:
    """A path name as URL path segments: each ``/``-separated segment
    percent-encoded on its own, the separators kept. Every Relay API URL built
    from a path name goes through here, so no name can reach another endpoint."""
    return "/".join(quote(segment, safe="") for segment in name.split("/"))


# The Relay's own RTSP server, loopback only (relay/relay.yml). Hold paths read through it.
RELAY_RTSP_URL = "rtsp://127.0.0.1:18554"
HOLD_PREFIX = "_hold/"


def hold_path_name(camera_id: str) -> str:
    """The Relay path that holds a Camera's Feed open. Device labels are
    kebab-case, so no Camera id starts with an underscore."""
    return HOLD_PREFIX + camera_id


def with_credentials(url: str, username: str, password: str) -> str:
    if not username:
        return url
    parts = urlsplit(url)
    netloc = f"{quote(username, safe='')}:{quote(password, safe='')}@{parts.netloc}"
    return urlunsplit(parts._replace(netloc=netloc))


def paths_for(devices: Iterable[Device], *, recording: RecordSettings | None = None,
              recorded: Iterable[str] = (), held: Iterable[str] = (),
              relay: RelayCredentials = RelayCredentials()) -> dict[str, RelayPath]:
    """The desired Relay paths, keyed by path name.

    One per Camera of every Device, named by the Camera's id, recording if
    the id is in ``recorded``. Plus a hold path for every Camera id in
    ``held``: the Relay reading that Camera's path from itself over loopback
    RTSP (as the Relay's internal user), always on. A Camera's path pulls only while it has a reader, so the
    hold keeps a Feed pulled with no browser watching (a Recording needs
    that), and adding or removing it never recreates the Camera's path or
    drops its viewers.

    A Device's credentials go only to its own host, and only over RTSPS if
    the Device is pinned. The API refuses a Camera on another host, or a
    plain ``rtsp://`` one on a pinned Device, but a config store written
    before it did may still hold one; that Camera is pulled without
    credentials (and so fails to play).
    """
    recorded, held = set(recorded), set(held)
    paths: dict[str, RelayPath] = {}
    for device in devices:
        for camera in device.cameras:
            gets_credentials = (same_host(device.address, camera.source_url)
                                and (not device.fingerprint or camera.source_url.startswith("rtsps://")))
            paths[camera.id] = RelayPath(
                source=(with_credentials(camera.source_url, device.username, device.password)
                        if gets_credentials else camera.source_url),
                # A pin means something only to an rtsps:// source.
                fingerprint=device.fingerprint if camera.source_url.startswith("rtsps://") else None,
                record=camera.id in recorded,
                recording=recording,
            )
            if camera.id in held:
                paths[hold_path_name(camera.id)] = RelayPath(
                    source=with_credentials(f"{RELAY_RTSP_URL}/{quote_path(camera.id)}", relay.user,
                                            relay.password),
                    fingerprint=None, on_demand=False)
    return paths


def video_size(path_state: dict[str, Any] | None) -> tuple[int, int] | None:
    """The received resolution in a path's runtime state: its first video
    track's codec properties (``tracks2[].codecProps``), or None."""
    for track in (path_state or {}).get("tracks2") or []:
        props = track.get("codecProps") or {}
        if props.get("width") and props.get("height"):
            return int(props["width"]), int(props["height"])
    return None


class RelayUnavailable(RuntimeError):
    pass


class RelayController:
    def __init__(self, api_url: str, *, interval: float = 2.0, client: httpx.AsyncClient | None = None,
                 credentials: RelayCredentials = RelayCredentials()):
        self._client = client or httpx.AsyncClient(base_url=api_url, timeout=5,
                                                   auth=credentials.httpx_auth())
        self._interval = interval
        self._desired: dict[str, RelayPath] = {}
        self._applied: dict[str, RelayPath] = {}
        self._lock = asyncio.Lock()
        self._wake = asyncio.Event()
        self._reconciled = asyncio.Event()  # set, and replaced, after every reconcile pass

    # -- desired state ----------------------------------------------------------

    def declare(self, paths: dict[str, RelayPath]) -> None:
        """Replace the desired path set. Applied on the next reconcile, which this wakes."""
        self._desired = dict(paths)
        self._wake.set()

    async def settled(self, name: str) -> None:
        """Return once the Relay holds the config last declared for ``name``
        (or no longer has the path, if none is declared). Waits as long as it
        takes, so callers bound it."""
        while self._applied.get(name) != self._desired.get(name):
            self._wake.set()
            await self._reconciled.wait()
            if self._applied.get(name) != self._desired.get(name):
                await asyncio.sleep(0.2)  # the Relay is down or refused it: don't spin

    async def ensure(self, name: str) -> None:
        """Make sure a declared path exists on the Relay right now, before a reader
        connects, even if the Relay restarted since the last reconcile.
        Raises RelayUnavailable while the Relay is down."""
        try:
            response = await self._client.get(f"/v3/config/paths/get/{quote_path(name)}")
        except httpx.HTTPError as exc:
            raise RelayUnavailable(repr(exc)) from exc
        if response.status_code == 404:
            await self.reconcile()

    # -- reading the Relay --------------------------------------------------------

    async def path_state(self, name: str) -> dict[str, Any] | None:
        """The Relay's runtime state for a path (``/v3/paths/get``), or None if it has none."""
        return await self._get_optional(f"/v3/paths/get/{quote_path(name)}")

    async def source_state(self, name: str) -> dict[str, Any] | None:
        """The pulled source's state and RTP counters (``/v3/paths/static-sources/get``)."""
        return await self._get_optional(f"/v3/paths/static-sources/get/{quote_path(name)}")

    # -- reconciling ------------------------------------------------------------

    async def run(self) -> None:
        """Reconcile forever: on every declare, and every interval regardless."""
        while True:
            self._wake.clear()
            try:
                await self.reconcile()
            except RelayUnavailable as exc:
                log.info("relay not reachable yet: %s", exc)
            try:
                await asyncio.wait_for(self._wake.wait(), self._interval)
            except TimeoutError:
                pass

    async def reconcile(self) -> None:
        async with self._lock:
            try:
                actual = await self._configured_names()
                for name in self._applied.keys() - actual:
                    del self._applied[name]  # the Relay restarted, or lost it some other way
                for name in actual - self._desired.keys():
                    if await self._apply("DELETE", f"/v3/config/paths/delete/{quote_path(name)}"):
                        self._applied.pop(name, None)
                for name, path in self._desired.items():
                    if name not in actual:
                        applied = await self._apply("POST", f"/v3/config/paths/add/{quote_path(name)}", path.config())
                    elif self._applied.get(name) != path:
                        applied = await self._apply("POST", f"/v3/config/paths/replace/{quote_path(name)}", path.config())
                    else:
                        continue
                    if applied:
                        self._applied[name] = path
            except httpx.HTTPError as exc:
                raise RelayUnavailable(repr(exc)) from exc
            finally:
                reconciled, self._reconciled = self._reconciled, asyncio.Event()
                reconciled.set()

    async def aclose(self) -> None:
        await self._client.aclose()

    # -- internals ----------------------------------------------------------------

    async def _configured_names(self) -> set[str]:
        names: set[str] = set()
        page = 0
        while True:
            body = (await self._call("GET", f"/v3/config/paths/list?itemsPerPage=500&page={page}")).json()
            names.update(item["name"] for item in body.get("items", []))
            page += 1
            if page >= body.get("pageCount", 1):
                return names

    async def _get_optional(self, url: str) -> dict[str, Any] | None:
        response = await self._client.get(url)
        if response.status_code == 404:
            return None
        response.raise_for_status()
        return response.json()

    async def _apply(self, method: str, url: str, body: dict[str, Any] | None = None) -> bool:
        """One config change. A refusal is logged and retried next pass; it never
        stops the other paths from being applied."""
        response = await self._client.request(method, url, json=body)
        if response.status_code >= 400:
            log.warning("relay refused %s %s (%s): %s", method, url, response.status_code, response.text)
            return False
        return True

    async def _call(self, method: str, url: str) -> httpx.Response:
        response = await self._client.request(method, url)
        response.raise_for_status()
        return response
