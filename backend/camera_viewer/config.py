"""Instance settings, read once from the environment.

Every setting is an environment variable with a default that matches the
image. The Relay's addresses must agree with ``relay/relay.yml``. The one
exception is ``CV_PASSWORD``, the instance's shared password: it has no
default, and ``check`` refuses settings without one.
"""

from __future__ import annotations

import os
import re
from collections.abc import Callable, Mapping
from dataclasses import dataclass, field
from pathlib import Path

from camera_viewer.disk import DiskThresholds
from camera_viewer.feed_status import Thresholds
from camera_viewer.maps import (
    IMAGERY_ATTRIBUTION_VARIABLE,
    IMAGERY_VARIABLE,
    TILES_ATTRIBUTION_VARIABLE,
    TILES_VARIABLE,
    TileServer,
    imagery_server,
    tile_server,
)
from camera_viewer.positions import PositionTimings
from camera_viewer.quality_auto import AutoThresholds
from camera_viewer.ui_certificate import valid_name


class ConfigError(Exception):
    """Settings the instance must not start with."""


@dataclass(frozen=True)
class Settings:
    http_host: str = "0.0.0.0"
    http_port: int = 8080
    config_dir: Path = Path("/config")
    captures_dir: Path = Path("/captures")
    frontend_dir: Path = Path(__file__).resolve().parents[2] / "frontend"
    relay_config: Path = Path("/etc/camera-viewer/relay.yml")
    relay_api_url: str = "http://127.0.0.1:19997"
    relay_whep_url: str = "http://127.0.0.1:18889"
    relay_reconcile_seconds: float = 2.0
    # The Relay's internal user, generated by the supervisor at every start;
    # empty only when the Relay runs without one (development).
    relay_user: str = ""
    relay_pass: str = field(default="", repr=False)
    feed_thresholds: Thresholds = field(default_factory=Thresholds)  # FEED_* variables
    feed_sample_seconds: float = 1.0
    # Browser-side: no new decoded frame for this long while Live is a Stall.
    # Not a Feed Status threshold (a Stall never reaches the Evaluator); it
    # reaches browsers in the `settings` event.
    stall_seconds: float = 2.0
    device_probe_seconds: float = 2.0
    certificate_check_seconds: float = 5.0
    # How often each reachable Device's `started` is read, so a restart gets its Quality
    # re-applied within this long (ADR 0009).
    quality_check_seconds: float = 10.0
    # How often each reachable Device's Camera configs are read as well, so a change by another
    # instance shows within this long even on a pinned Camera with no write pending.
    quality_config_check_seconds: float = 60.0
    quality_thresholds: AutoThresholds = field(default_factory=AutoThresholds)  # QUALITY_* variables
    position_timings: PositionTimings = field(default_factory=PositionTimings)  # POSITION_* variables
    # The online tile server the map falls back on without a Map Extract (CV_MAP_TILES, #62).
    map_tiles: TileServer | None = None
    # The imagery server the Satellite Basemap draws (CV_MAP_IMAGERY, #83); no default provider.
    map_imagery: TileServer | None = None
    # Timed Recordings' preset durations in seconds; tests shorten them.
    recording_presets: tuple[int, ...] = (30, 60, 300)
    snapshot_max_bytes: int = 64 * 1024 * 1024
    disk_thresholds: DiskThresholds = field(default_factory=DiskThresholds)  # CV_DISK_* variables
    disk_check_seconds: float = 5.0
    password: str = field(default="", repr=False)
    session_max_age_seconds: int = 14 * 24 * 3600
    # Login throttling per client address: this many wrong passwords in a
    # row lock it out for the lockout, doubled for each further lockout.
    login_max_failures: int = 10
    login_lockout_seconds: float = 30.0
    # The UI is HTTPS unless CV_TLS is off (ADR 0014). A supplied PEM
    # certificate (chain) and key, paths inside the container, both or
    # neither; without them the instance makes its own (ui_certificate).
    tls_enabled: bool = True
    tls_cert: Path | None = None
    tls_key: Path | None = None
    # Extra names for the generated certificate (CV_TLS_SANS), and the address
    # browsers reach the instance on (CV_HOST_IP), which it names too.
    tls_names: tuple[str, ...] = ()
    host_ip: str = ""

    @property
    def tls(self) -> bool:
        return self.tls_enabled

    @property
    def tls_supplied(self) -> bool:
        return self.tls_cert is not None or self.tls_key is not None

    @classmethod
    def from_env(cls, env: Mapping[str, str] | None = None) -> Settings:
        """Read every setting from ``env``. A variable that is unset or empty
        keeps its default; one that can't be read raises ``ConfigError``
        naming it, like every other setting the instance refuses."""
        env = os.environ if env is None else env
        d = cls()

        def text(name: str, default: str) -> str:
            value = env.get(name, "")
            return value if value.strip() else default

        def number(name: str, default, kind=float):
            value = env.get(name, "")
            if not value.strip():
                return default
            try:
                return kind(value)
            except ValueError:
                what = "a whole number" if kind is int else "a number"
                raise ConfigError(f"{name} must be {what}, got {value!r}") from None

        try:
            feed = feed_thresholds(env)
            disk_thresholds = DiskThresholds.from_env(env)
            quality = quality_thresholds(env)
            positions = position_timings(env)
            tiles = tile_server(env.get(TILES_VARIABLE, ""), env.get(TILES_ATTRIBUTION_VARIABLE, ""))
            imagery = imagery_server(env.get(IMAGERY_VARIABLE, ""), env.get(IMAGERY_ATTRIBUTION_VARIABLE, ""))
        except ValueError as exc:
            raise ConfigError(str(exc)) from None
        return cls(
            http_host=text("CV_HTTP_HOST", d.http_host),
            http_port=number("CV_HTTP_PORT", d.http_port, int),
            config_dir=Path(text("CV_CONFIG_DIR", str(d.config_dir))),
            captures_dir=Path(text("CV_CAPTURES_DIR", str(d.captures_dir))),
            frontend_dir=Path(text("CV_FRONTEND_DIR", str(d.frontend_dir))),
            relay_config=Path(text("CV_RELAY_CONFIG", str(d.relay_config))),
            relay_api_url=text("CV_RELAY_API_URL", d.relay_api_url),
            relay_whep_url=text("CV_RELAY_WHEP_URL", d.relay_whep_url),
            relay_reconcile_seconds=number("CV_RELAY_RECONCILE_SECONDS", d.relay_reconcile_seconds),
            relay_user=env.get("CV_RELAY_USER", d.relay_user),
            relay_pass=env.get("CV_RELAY_PASS", d.relay_pass),
            feed_thresholds=feed,
            feed_sample_seconds=number("CV_FEED_SAMPLE_SECONDS", d.feed_sample_seconds),
            stall_seconds=number("FEED_STALL_SECONDS", d.stall_seconds),
            device_probe_seconds=number("CV_DEVICE_PROBE_SECONDS", d.device_probe_seconds),
            certificate_check_seconds=number("CV_CERTIFICATE_CHECK_SECONDS", d.certificate_check_seconds),
            quality_check_seconds=number("CV_QUALITY_CHECK_SECONDS", d.quality_check_seconds),
            quality_config_check_seconds=number("CV_QUALITY_CONFIG_CHECK_SECONDS", d.quality_config_check_seconds),
            quality_thresholds=quality,
            position_timings=positions,
            map_tiles=tiles,
            map_imagery=imagery,
            recording_presets=_presets(env.get("CV_RECORDING_PRESETS"), d.recording_presets),
            snapshot_max_bytes=number("CV_SNAPSHOT_MAX_BYTES", d.snapshot_max_bytes, int),
            disk_thresholds=disk_thresholds,
            disk_check_seconds=number("CV_DISK_CHECK_SECONDS", d.disk_check_seconds),
            password=env.get("CV_PASSWORD", d.password),
            session_max_age_seconds=number("CV_SESSION_MAX_AGE_SECONDS", d.session_max_age_seconds, int),
            login_max_failures=number("CV_LOGIN_MAX_FAILURES", d.login_max_failures, int),
            login_lockout_seconds=number("CV_LOGIN_LOCKOUT_SECONDS", d.login_lockout_seconds),
            tls_enabled=_switch(env, "CV_TLS", d.tls_enabled),
            tls_cert=_optional_path(env.get("CV_TLS_CERT")),
            tls_key=_optional_path(env.get("CV_TLS_KEY")),
            tls_names=_names(env, "CV_TLS_SANS"),
            host_ip=_name(env, "CV_HOST_IP"),
        )


Rules = Mapping[str, tuple[type, Callable[[float], bool]]]


def _positive(value: float) -> bool:
    return value > 0


def _non_negative(value: float) -> bool:
    return value >= 0


FEED_RULES: Rules = {
    "down_after_seconds": (float, _non_negative),
    "degraded_window_seconds": (float, _positive),
    "rtp_loss_max_percent": (float, _non_negative),
    "errored_frames_max": (int, _non_negative),
}
QUALITY_RULES: Rules = {
    "window_seconds": (float, _positive),
    "down_lossy_windows": (int, _positive),
    "down_lookback_windows": (int, _positive),
    "up_clean_seconds": (float, _positive),
    "up_trial_seconds": (float, _positive),
    "up_wait_max_seconds": (float, _positive),
    "up_disruptive_clean_seconds": (float, _positive),
}


POSITION_RULES: Rules = {
    "stale_seconds": (float, _positive),
    "probe_seconds": (float, _positive),
    "trail_seconds": (float, _positive),
    # No faster than the 1 Hz of Position Demand, and within what the Sidecar takes (ADR 0010).
    "idle_seconds": (float, lambda value: 1 <= value <= 3600),
    "demand_linger_seconds": (float, _positive),
}


def feed_thresholds(env: Mapping[str, str]) -> Thresholds:
    """Feed Status thresholds from ``FEED_<FIELD>`` variables; unset or empty ones keep their
    defaults, and other ``FEED_*`` variables (a leftover bitrate line) are ignored. Raises
    ``ValueError`` naming a variable it can't use."""
    return Thresholds(**_read_overrides(env, "FEED", FEED_RULES))


def quality_thresholds(env: Mapping[str, str]) -> AutoThresholds:
    """Auto's timings from ``QUALITY_<FIELD>`` variables, as ``feed_thresholds`` reads its own.
    Raises ``ValueError`` naming a variable that can't be read or doesn't fit the others."""
    thresholds = AutoThresholds(**_read_overrides(env, "QUALITY", QUALITY_RULES))
    if thresholds.down_lossy_windows > thresholds.down_lookback_windows:
        raise ValueError("QUALITY_DOWN_LOSSY_WINDOWS can't be more than QUALITY_DOWN_LOOKBACK_WINDOWS "
                         f"({thresholds.down_lossy_windows} > {thresholds.down_lookback_windows})")
    if thresholds.up_wait_max_seconds < thresholds.up_clean_seconds:
        raise ValueError("QUALITY_UP_WAIT_MAX_SECONDS can't be less than QUALITY_UP_CLEAN_SECONDS "
                         f"({thresholds.up_wait_max_seconds:g} < {thresholds.up_clean_seconds:g})")
    return thresholds


def position_timings(env: Mapping[str, str]) -> PositionTimings:
    """The Position Service's timings from ``POSITION_<FIELD>`` variables, as ``feed_thresholds``
    reads its own. Raises ``ValueError`` naming a variable it can't use."""
    return PositionTimings(**_read_overrides(env, "POSITION", POSITION_RULES))


def _read_overrides(env: Mapping[str, str], prefix: str, rules: Rules) -> dict[str, float]:
    """The values ``<PREFIX>_<FIELD>`` variables set, read with each field's kind and checked
    with its rule. Unset or empty variables are left out, so their defaults stand; other variables
    with the prefix are ignored. Raises ``ValueError`` naming the variable it can't use."""
    overrides = {}
    for field_name, (kind, valid) in rules.items():
        name = f"{prefix}_{field_name.upper()}"
        if not env.get(name, "").strip():
            continue
        try:
            value = kind(env[name])
        except ValueError:
            raise ValueError(f"{name} must be a {kind.__name__}, got {env[name]!r}") from None
        if not valid(value):
            raise ValueError(f"{name} is out of range: {env[name]!r}")
        overrides[field_name] = value
    return overrides


def _switch(env: Mapping[str, str], name: str, default: bool) -> bool:
    value = env.get(name, "").strip().lower()
    if not value:
        return default
    if value not in ("on", "off"):
        raise ConfigError(f"{name} must be on or off, got {env[name]!r}")
    return value == "on"


def _names(env: Mapping[str, str], name: str) -> tuple[str, ...]:
    """Certificate names separated by commas or spaces, each an IP address or DNS name."""
    names = tuple(part for part in re.split(r"[,\s]+", env.get(name, "")) if part)
    for part in names:
        if not valid_name(part):
            raise ConfigError(f"{name} must list IP addresses or DNS names, separated by commas; "
                              f"{part!r} is neither")
    return names


def _name(env: Mapping[str, str], name: str) -> str:
    value = env.get(name, "").strip()
    if value and not valid_name(value):
        raise ConfigError(f"{name} must be an IP address or DNS name, got {env[name]!r}")
    return value


def _optional_path(value: str | None) -> Path | None:
    return Path(value) if value and value.strip() else None


def _presets(value: str | None, default: tuple[int, ...]) -> tuple[int, ...]:
    """``"30,60,300"`` -> ``(30, 60, 300)``; ``check`` refuses anything else."""
    if value is None or not value.strip():
        return default
    try:
        return tuple(int(part) for part in value.split(","))
    except ValueError:
        return ()


def check(settings: Settings) -> None:
    """Raise ``ConfigError`` unless the instance can safely start."""
    if not settings.password.strip():
        raise ConfigError("CV_PASSWORD is not set: the instance needs a shared password "
                          "(set CV_PASSWORD in the environment, e.g. in .env next to compose.yaml)")
    presets = settings.recording_presets
    if not presets or any(seconds <= 0 for seconds in presets) or len(set(presets)) != len(presets):
        raise ConfigError("CV_RECORDING_PRESETS must be distinct whole numbers of seconds above zero, "
                          "separated by commas (the default is 30,60,300)")
    if settings.quality_check_seconds <= 0:
        raise ConfigError("CV_QUALITY_CHECK_SECONDS must be a number of seconds above zero (the default is 10)")
    if settings.quality_config_check_seconds <= 0:
        raise ConfigError("CV_QUALITY_CONFIG_CHECK_SECONDS must be a number of seconds above zero "
                          "(the default is 60)")
    if settings.login_max_failures < 1 or settings.login_lockout_seconds <= 0:
        raise ConfigError("CV_LOGIN_MAX_FAILURES must be at least 1 and CV_LOGIN_LOCKOUT_SECONDS above zero")
    if settings.tls_supplied and not settings.tls_enabled:
        raise ConfigError("CV_TLS is off, but CV_TLS_CERT or CV_TLS_KEY is set: remove them to serve the UI "
                          "over plain HTTP, or turn CV_TLS on to serve it over HTTPS with that certificate")
    for variable, server in ((TILES_VARIABLE, settings.map_tiles), (IMAGERY_VARIABLE, settings.map_imagery)):
        if settings.tls and server and not server.url.lower().startswith("https://"):
            raise ConfigError(f"{variable} must be an https:// template while the UI is served over HTTPS: "
                              "browsers block http:// tiles on an HTTPS page, so the map would stay blank")
    if settings.tls_supplied:
        if settings.tls_cert is None or settings.tls_key is None:
            raise ConfigError("CV_TLS_CERT and CV_TLS_KEY go together: set both to serve the UI "
                              "over HTTPS with your certificate, or neither for one the instance makes")
        for name, path in (("CV_TLS_CERT", settings.tls_cert), ("CV_TLS_KEY", settings.tls_key)):
            if not path.is_file():
                raise ConfigError(f"{name} is {str(path)!r}, which is not a readable file in the "
                                  "container (put it under ./config and give the /config/... path)")
