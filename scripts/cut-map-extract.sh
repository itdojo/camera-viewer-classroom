#                                                                     ARGUMENTS
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
usage() {
    cat <<'USAGE'
cut-map-extract.sh — cuts a Map Extract for Camera Viewer's map.

Usage: scripts/cut-map-extract.sh (--bbox W,S,E,N | --place NAME)... [options]

  -b, --bbox W,S,E,N     An area, as west,south,east,north in decimal
                         degrees (longitude first), e.g.
                         -0.1270,51.4985,-0.1200,51.5030.
  -p, --place NAME       An area looked up by name instead, through
                         OpenStreetMap's Nominatim, e.g. "Monterey, CA".
                         Repeat --bbox and --place, in any mix, for several
                         areas: they all go into the one extract.
  -w, --world            Add the whole planet at zooms 0-6 (about 45 MB),
                         so a zoomed-out map shows coastlines and countries
                         everywhere, not only your areas. Needs --maxzoom 7
                         or more, since the areas then start at zoom 7.
  -n, --name NAME        File name, without .pmtiles: lowercase letters,
                         digits and hyphens. Default: from --place when it
                         is the only area, otherwise "extract".
  -z, --maxzoom N        Deepest zoom to keep, 0-15 (default 15, street
                         level). Each level less roughly quarters the size.
      --build YYYYMMDD   A planet build to cut from (default: the newest).
  -o, --maps-dir DIR     Where to write it (default: config/maps next to
                         compose.yaml, the folder the instance reads).
  -f, --force            Replace an extract of the same name.
  -y, --yes              Don't ask before downloading.
  -h, --help             Show this message.
USAGE
}

parse_args() {
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --bbox|-b)      [[ $# -ge 2 ]] || { log_err "$1 needs a value."; exit 2; }
                            AREAS+=("bbox:$2"); shift ;;
            --place|-p)     [[ $# -ge 2 ]] || { log_err "$1 needs a value."; exit 2; }
                            AREAS+=("place:$2"); shift ;;
            --world|-w)     WORLD=1 ;;
            --name|-n)      [[ $# -ge 2 ]] || { log_err "$1 needs a value."; exit 2; }
                            NAME="$2"; shift ;;
            --maxzoom|-z)   [[ $# -ge 2 ]] || { log_err "$1 needs a value."; exit 2; }
                            MAXZOOM="$2"; shift ;;
            --build)        [[ $# -ge 2 ]] || { log_err "$1 needs a value."; exit 2; }
                            BUILD="$2"; shift ;;
            --maps-dir|-o)  [[ $# -ge 2 ]] || { log_err "$1 needs a value."; exit 2; }
                            MAPS_DIR="$2"; shift ;;
            --force|-f)     FORCE=1 ;;
            --yes|-y)       ASSUME_YES=1 ;;
            --help|-h)      usage; exit 0 ;;
            *)              log_err "Unknown option: $1"; usage >&2; exit 2 ;;
        esac
        shift
    done
    # Everything is checked before anything is fetched, so a typo costs nothing.
    if (( ${#AREAS[@]} == 0 )); then
        log_err "Give the area as --bbox W,S,E,N or --place NAME, and repeat either for several areas."
        exit 2
    fi
    local area
    for area in "${AREAS[@]}"; do
        if [[ "$area" == bbox:* ]] && ! check_bbox "${area#bbox:}"; then
            log_err "--bbox ${area#bbox:} is not west,south,east,north: four numbers, west < east and south < north, within ±180 and ±90."
            exit 2
        fi
    done
    if [[ ! "$MAXZOOM" =~ ^[0-9]+$ ]] || (( MAXZOOM > 15 )); then
        log_err "--maxzoom $MAXZOOM must be a whole number from 0 to 15."
        exit 2
    fi
    if [[ -n "$WORLD" ]] && (( MAXZOOM <= WORLD_MAXZOOM )); then
        log_err "--world already covers zooms 0-$WORLD_MAXZOOM everywhere, so --maxzoom must be $(( WORLD_MAXZOOM + 1 )) or more with it."
        exit 2
    fi
    if [[ -n "$BUILD" && ! "$BUILD" =~ ^[0-9]{8}$ ]]; then
        log_err "--build $BUILD must be a build date, YYYYMMDD."
        exit 2
    fi
    if [[ -z "$NAME" && ${#AREAS[@]} -eq 1 && "${AREAS[0]}" == place:* ]]; then
        NAME="$(slug "${AREAS[0]#place:}")"
    fi
    [[ -n "$NAME" ]] || NAME="extract"
    if [[ ! "$NAME" =~ ^[a-z0-9]+(-[a-z0-9]+)*$ ]]; then
        log_err "--name $NAME may hold only lowercase letters, digits and hyphens."
        exit 2
    fi
    OUTPUT="$MAPS_DIR/$NAME.pmtiles"
    if [[ -n "$WORLD" ]]; then
        WORLD_PART="$OUTPUT.world.partial"
        AREAS_PART="$OUTPUT.areas.partial"
    fi
}

# "Monterey, CA" -> "monterey-ca"
slug() {
    printf '%s' "$1" | tr '[:upper:]' '[:lower:]' | tr -cs 'a-z0-9' '-' | sed -e 's/^-*//' -e 's/-*$//'
}

# True if $1 is west,south,east,north with west < east and south < north.
check_bbox() {
    local number='-?[0-9]+(\.[0-9]+)?'
    [[ "$1" =~ ^$number,$number,$number,$number$ ]] || return 1
    awk -F, '{ exit !($1 < $3 && $2 < $4 && $1 >= -180 && $3 <= 180 && $2 >= -90 && $4 <= 90) }' <<<"$1"
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                         TOOLS
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
check_tools() {
    local tool
    for tool in curl python3; do
        if ! command -v "$tool" >/dev/null 2>&1; then
            log_err "$tool is not installed. Install it with your package manager and re-run."
            exit 1
        fi
    done
    if ! command -v pmtiles >/dev/null 2>&1; then
        log_err "The pmtiles tool is not installed. Download the build for this machine from"
        printf '         %s\n' "https://github.com/protomaps/go-pmtiles/releases" >&2
        printf '         %s\n' "and put its pmtiles binary on your PATH (e.g. /usr/local/bin), then re-run." >&2
        exit 1
    fi
    # Asked here, before anything is downloaded, rather than found out after the cut.
    if [[ -n "$WORLD" ]] && ! pmtiles merge --help >/dev/null 2>&1; then
        log_err "--world needs the pmtiles merge command, which this pmtiles lacks (it arrived in 1.29.1)."
        printf '         %s\n' "Download 1.31.2 or later from https://github.com/protomaps/go-pmtiles/releases" >&2
        printf '         %s\n' "and put it on your PATH in place of this one, then re-run." >&2
        exit 1
    fi
    log_ok "pmtiles is installed: $(pmtiles version 2>/dev/null | head -n 1)."
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                          AREA
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
# Every area becomes one polygon of a GeoJSON MultiPolygon, the region that
# `pmtiles extract --region` cuts, so several areas make one extract. Several
# extracts drawn together would repeat every label (README, ADR 0015).
resolve_areas() {
    local area
    for area in "${AREAS[@]}"; do
        if [[ "$area" == bbox:* ]]; then
            BBOXES+=("${area#bbox:}")
            log_ok "Area: ${area#bbox:} (west,south,east,north)."
        else
            look_up_place "${area#place:}"
        fi
    done
    REGION="$(mktemp "${TMPDIR:-/tmp}/cut-map-extract.XXXXXX")"
    python3 -c '
import json, sys
polygons = []
for bbox in sys.argv[1:]:
    west, south, east, north = (float(n) for n in bbox.split(","))
    polygons.append([[[west, south], [east, south], [east, north], [west, north], [west, south]]])
print(json.dumps({"type": "MultiPolygon", "coordinates": polygons}))
' "${BBOXES[@]}" > "$REGION"
    if (( ${#BBOXES[@]} > 1 )); then
        log_ok "${#BBOXES[@]} areas go into the one extract."
    fi
}

# A place name becomes the bounding box Nominatim gives for its best match,
# printed with the match's full name so a wrong "Springfield" is caught here.
look_up_place() {
    local place="$1" answer found bbox
    log_step "Looking up \"$place\" in OpenStreetMap's Nominatim..."
    answer="$(curl -fsS -G -A "$USER_AGENT" --data-urlencode "q=$place" \
        -d format=jsonv2 -d limit=1 "$GEOCODER_URL")"
    found="$(python3 -c '
import json, sys
matches = json.loads(sys.argv[1])
if matches:
    south, north, west, east = matches[0]["boundingbox"]
    print(f"{west},{south},{east},{north}")
    print(matches[0]["display_name"])
' "$answer")"
    if [[ -z "$found" ]]; then
        log_err "Nominatim found nothing called \"$place\". Try a fuller name, or give --bbox."
        exit 1
    fi
    bbox="$(head -n 1 <<<"$found")"
    BBOXES+=("$bbox")
    log_ok "Found $(tail -n 1 <<<"$found")."
    log_info "Area: $bbox (west,south,east,north). If that is the wrong place, re-run with --bbox."
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                  PLANET BUILD
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
# Protomaps publishes a planet build most days and lists each with its tiles
# schema version. The newest is taken unless --build names one, and either
# must be of the schema the vendored style draws.
resolve_build() {
    log_step "Reading the list of planet builds..."
    local builds chosen
    builds="$(curl -fsS "$BUILDS_URL")"
    chosen="$(python3 -c '
import json, sys
builds, wanted = json.loads(sys.argv[1]), sys.argv[2]
keys = [b for b in builds if b["key"] == f"{wanted}.pmtiles"] if wanted else builds[-1:]
if keys:
    print(keys[0]["key"].removesuffix(".pmtiles"), keys[0]["version"])
' "$builds" "$BUILD")"
    if [[ -z "$chosen" ]]; then
        log_err "There is no planet build $BUILD. Leave out --build for the newest."
        exit 1
    fi
    BUILD="${chosen% *}"
    BUILD_VERSION="${chosen#* }"
    if [[ "${BUILD_VERSION%%.*}" != "$SCHEMA_MAJOR" ]]; then
        log_err "Planet build $BUILD has tiles schema $BUILD_VERSION, but Camera Viewer's map style draws schema $SCHEMA_MAJOR.x."
        printf '         %s\n' "Pick an older build with --build, or update frontend/vendor/protomaps-basemaps (ADR 0011)." >&2
        exit 1
    fi
    log_ok "Planet build $BUILD (tiles schema $BUILD_VERSION)."
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                       EXTRACT
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
# The archive size a dry run of `pmtiles extract <args>` reports, such as
# "2.7 MB", or nothing if it reports none.
measure() {
    pmtiles extract "$@" --dry-run 2>&1 | sed -n 's/.*archive size of //p' | tail -n 1
}

# The sum of sizes as pmtiles prints them (go-humanize: decimal units, one
# decimal below 10), in the same form; "unknown" if any of them is.
add_sizes() {
    python3 -c '
import sys
units = ["B", "kB", "MB", "GB", "TB", "PB", "EB"]
try:
    total = sum(float(n) * 1000 ** units.index(u) for n, u in (size.split() for size in sys.argv[1:]))
except ValueError:
    print("unknown")
    sys.exit()
power = 0
while total >= 1000 and power < len(units) - 1:
    total, power = total / 1000, power + 1
print(f"{total:.1f} {units[power]}" if total < 10 else f"{total:.0f} {units[power]}")
' "$@"
}

# The Confirmation rule (qol script-design.md): --yes skips the prompt, then a
# non-TTY stdin skips it, otherwise ask and default to No. Not ask_confirm
# alone, because its non-TTY rule returns the default, which would make a
# piped or scripted run decline; so the non-TTY case is decided here first.
confirm_download() {
    if [[ -n "$ASSUME_YES" || ! -t 0 ]]; then return 0; fi
    ask_confirm "$1" N
}

# A dry run first says how big the extract will be, the world base included.
# The cut is written as .partial and renamed when complete: the instance
# reads only *.pmtiles, so it never picks up half a file.
#
# With --world the planet's low zooms and the areas from the next zoom up
# are cut separately, then merged; `pmtiles merge` refuses inputs that share
# a tile, and these share none. The areas go first, because merge copies the
# header's centre from its first input.
#
# An existing extract is kept without touching the network for builds.
ensure_extract() {
    if [[ -e "$OUTPUT" && -z "$FORCE" ]]; then
        log_phase "EXTRACT"
        log_ok "$OUTPUT already exists; keeping it. Pass --force to cut it again."
        EXTRACT_ACTION="kept"
        return
    fi
    log_phase "PLANET BUILD"
    resolve_build
    log_phase "EXTRACT"
    local source="$PLANET_URL/$BUILD.pmtiles" area_zoom=$(( WORLD_MAXZOOM + 1 )) world_size areas_size
    log_step "Measuring the extract..."
    if [[ -n "$WORLD" ]]; then
        world_size="$(measure "$source" "$WORLD_PART" --maxzoom="$WORLD_MAXZOOM")"
        areas_size="$(measure "$source" "$AREAS_PART" --region="$REGION" --minzoom="$area_zoom" --maxzoom="$MAXZOOM")"
        log_info "World base: ${world_size:-unknown} (zoom 0 to $WORLD_MAXZOOM, the whole planet)."
        log_info "Areas: ${areas_size:-unknown} (zoom $area_zoom to $MAXZOOM)."
        log_info "Size: $(add_sizes "$world_size" "$areas_size") in all."
    else
        areas_size="$(measure "$source" "$OUTPUT.partial" --region="$REGION" --maxzoom="$MAXZOOM")"
        log_info "Size: ${areas_size:-unknown} (zoom 0 to $MAXZOOM)."
    fi
    if ! confirm_download "Download it into $OUTPUT?"; then
        log_info "Nothing downloaded."
        EXTRACT_ACTION="declined"
        return
    fi
    mkdir -p "$MAPS_DIR"
    if [[ -n "$WORLD" ]]; then
        log_step "Cutting the world base from planet build $BUILD..."
        pmtiles extract "$source" "$WORLD_PART" --maxzoom="$WORLD_MAXZOOM"
        log_step "Cutting the areas from planet build $BUILD..."
        pmtiles extract "$source" "$AREAS_PART" --region="$REGION" --minzoom="$area_zoom" --maxzoom="$MAXZOOM"
        log_step "Merging them into $NAME.pmtiles..."
        pmtiles merge "$AREAS_PART" "$WORLD_PART" "$OUTPUT.partial"
    else
        log_step "Cutting $NAME.pmtiles from planet build $BUILD..."
        pmtiles extract "$source" "$OUTPUT.partial" --region="$REGION" --maxzoom="$MAXZOOM"
    fi
    mv -f "$OUTPUT.partial" "$OUTPUT"
    log_ok "$OUTPUT is written."
    EXTRACT_ACTION="cut"
}

# Several extracts are allowed, but only the newest is drawn.
report_others() {
    local other
    for other in "$MAPS_DIR"/*.pmtiles; do
        if [[ -f "$other" && "$other" != "$OUTPUT" ]]; then
            log_warn "$MAPS_DIR also holds $(basename "$other"). The instance draws only the most recently modified extract; remove the others."
        fi
    done
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                          MAIN
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
main() {
    parse_args "$@"
    banner "MAP EXTRACT" "$OUTPUT"
    check_for_root
    check_tools

    log_phase "AREA"
    resolve_areas

    ensure_extract
    report_others

    case "$EXTRACT_ACTION" in
        cut)      log_complete "MAP EXTRACT READY" ;;
        kept)     log_complete "NOTHING TO DO — THE EXTRACT ALREADY EXISTS" ;;
        declined) log_complete "NOTHING DOWNLOADED" ;;
    esac
    if [[ "$EXTRACT_ACTION" != "declined" ]]; then
        log_next "Restart the instance to use it:  docker compose restart"
        log_next "Its map data is © OpenStreetMap contributors (ODbL); the map shows that attribution."
    fi
    echo
}

main "$@"
