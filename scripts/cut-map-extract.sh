handle_ctrl_c() {
    echo
    log_err "Interrupted. Re-run to finish; a half-cut extract is never left as a .pmtiles file."
    exit 130
}

handle_err() {
    log_err "Failed at line $1 (exit $2). No existing extract was touched."
}

check_for_root() {
    if [[ "$(id -u)" -eq 0 ]]; then
        log_err "Do not run as root. The extract must be owned by your user."
        exit 1
    fi
}

# The region file and the world base's two parts serve one run only, so they
# go however it ends. A $OUTPUT.partial left by a failed cut is replaced by
# the next run, as before.
clean_up() {
    if [[ -n "$REGION" ]]; then rm -f "$REGION"; fi
    if [[ -n "$WORLD_PART" ]]; then rm -f "$WORLD_PART" "$AREAS_PART"; fi
}

trap handle_ctrl_c INT
