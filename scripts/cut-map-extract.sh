#!/usr/bin/env bash
#
# cut-map-extract.sh
#
# Cuts a Map Extract (one .pmtiles file of OpenStreetMap data) for one or
# more deployment areas from the Protomaps planet build, while you still have
# internet, and writes it into the instance's config/maps folder. The
# instance then draws it under its maps with no network at all. --world adds
# the whole planet at low zoom to the same file.
#
# Targets:
#   - macOS                               (bash, curl, python3)
#   - Debian / Ubuntu / Raspberry Pi OS   (bash, curl, python3)
#
# Needs the pmtiles CLI (go-pmtiles) on PATH, from its official releases:
# https://github.com/protomaps/go-pmtiles/releases
#
# Usage:  scripts/cut-map-extract.sh --bbox W,S,E,N [options]
#         scripts/cut-map-extract.sh --place "Monterey, California" [options]
#         scripts/cut-map-extract.sh --place "Monterey, CA" --place "Fort Ord, CA" --world
# Do not run as root.
#
# The script is idempotent: an extract that already exists is kept and
# reported, never overwritten, unless --force asks for a new one.
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒

