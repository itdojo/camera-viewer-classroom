gen-cert.sh — certificate and credentials for a Device Kit Device.

Usage: ./gen-cert.sh [options] [VARIANT_DIR]

  VARIANT_DIR            Kit variant directory (default: current directory).
                         Writes VARIANT_DIR/certs/server.{key,crt} and, if
                         missing, VARIANT_DIR/.env with the instance user.
  -s, --san NAME         Extra DNS name or IP for the certificate. Repeatable.
                         localhost, 127.0.0.1, ::1 and this host's name are
                         always included.
  -o, --certs-dir DIR    Write the certificate here instead.
  -e, --env-file FILE    Write credentials here instead of VARIANT_DIR/.env.
  -f, --force            Replace an existing certificate. The Device's
                         fingerprint changes and Camera Viewer must re-pin it.
  -c, --camera PATH      The webcam a camera variant (usb) captures from,
                         saved as USB_CAMERA in the env file. Use its
                         /dev/v4l/by-id/...-video-index0 path, or just the
                         name as `ls /dev/v4l/by-id` prints it. Without it,
                         the one webcam attached is found by itself.
  -h, --help             Show this message.
USAGE
}

parse_args() {
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --san|-s)        [[ $# -ge 2 ]] || { log_err "$1 needs a value."; exit 2; }
                             EXTRA_SANS+=("$2"); shift ;;
            --certs-dir|-o)  [[ $# -ge 2 ]] || { log_err "$1 needs a value."; exit 2; }
                             CERTS_DIR="$2"; shift ;;
            --env-file|-e)   [[ $# -ge 2 ]] || { log_err "$1 needs a value."; exit 2; }
                             ENV_FILE="$2"; shift ;;
            --force|-f)      FORCE=1 ;;
            --camera|-c)     [[ $# -ge 2 ]] || { log_err "$1 needs a value."; exit 2; }
                             CAMERA="$2"; shift ;;
            --help|-h)       usage; exit 0 ;;
            -*)              log_err "Unknown option: $1"; usage >&2; exit 2 ;;
            *)               VARIANT_DIR="$1" ;;
        esac
        shift
    done
    # `ls /dev/v4l/by-id` prints bare names, so a name without a slash is
    # looked up there.
    if [[ -n "$CAMERA" && "$CAMERA" != */* ]]; then
        CAMERA="$V4L_BY_ID_DIR/$CAMERA"
    fi
    # Checked before anything is written, so a typo leaves no half-made Device.
    if [[ -n "$CAMERA" && ! -c "$CAMERA" ]]; then
        log_err "--camera $CAMERA is not a video device."
        local candidate listed=0
        for candidate in "$V4L_BY_ID_DIR"/*-video-index0; do
            if [[ -c "$candidate" ]]; then
                (( listed )) || printf '         Webcams attached now:\n' >&2
                printf '         --camera %s\n' "$candidate" >&2
                listed=1
            fi
        done
        (( listed )) || printf '         No webcam found in %s. Plug one in and re-run.\n' "$V4L_BY_ID_DIR" >&2
        exit 2
    fi
    [[ -n "$CERTS_DIR" ]] || CERTS_DIR="$VARIANT_DIR/certs"
    [[ -n "$ENV_FILE" ]]  || ENV_FILE="$VARIANT_DIR/.env"
    KEY_FILE="$CERTS_DIR/server.key"
    CERT_FILE="$CERTS_DIR/server.crt"
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                  REQUIREMENTS
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
check_openssl() {
    if ! command -v openssl >/dev/null 2>&1; then
        log_err "openssl is not installed. Install it (sudo apt-get install openssl) and re-run."
        exit 1
    fi
    log_info "Using $(openssl version)."
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                   CERTIFICATE
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
# One certificate serves both RTSPS and the HTTPS API. Camera Viewer pins it
# by SHA-256 fingerprint (MediaMTX `sourceFingerprint`), so no CA is involved.

# Build the subjectAltName value. Names that look like IPs become IP entries.
san_list() {
    local names=("localhost" "127.0.0.1" "::1")
    local host
    host="$(hostname 2>/dev/null || true)"
    [[ -n "$host" ]] && names+=("$host")
    names+=("${EXTRA_SANS[@]}")

    local out="" name
    for name in "${names[@]}"; do
        if [[ "$name" =~ ^[0-9.]+$ || "$name" == *:* ]]; then
            out+="${out:+,}IP:$name"
        else
            out+="${out:+,}DNS:$name"
        fi
    done
    printf '%s' "$out"
}

ensure_certificate() {
    if [[ -f "$KEY_FILE" && -f "$CERT_FILE" && -z "$FORCE" ]]; then
        log_ok "Certificate already exists in $CERTS_DIR; keeping it."
        CERT_ACTION="kept"
        return
    fi

    log_step "Generating a self-signed certificate in $CERTS_DIR..."
    mkdir -p "$CERTS_DIR"
    local tmp_key="$KEY_FILE.tmp.$$"
    local tmp_cert="$CERT_FILE.tmp.$$"
    (
        umask 077
        openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 \
            -nodes -keyout "$tmp_key" -out "$tmp_cert" -days "$CERT_DAYS" \
            -subj "/CN=$(hostname 2>/dev/null || echo device-kit)" \
            -addext "subjectAltName=$(san_list)"
    )
    # MediaMTX in the container reads the key as root, so 0600 is enough.
    chmod 600 "$tmp_key"
    chmod 644 "$tmp_cert"
    mv -f "$tmp_key" "$KEY_FILE"
    mv -f "$tmp_cert" "$CERT_FILE"
    log_ok "Certificate is generated."
    CERT_ACTION="generated"
}

# MediaMTX `sourceFingerprint` format: SHA-256 of the DER cert, lowercase hex,
# no colons.
read_fingerprint() {
    FINGERPRINT="$(openssl x509 -in "$CERT_FILE" -noout -fingerprint -sha256 \
        | sed 's/^.*=//; s/://g' | tr 'A-F' 'a-f')"
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                   CREDENTIALS
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
# The instance user is who Camera Viewer logs in as. Hex keeps the password
# safe inside rtsps:// URLs without escaping.
ensure_env_file() {
    if [[ -f "$ENV_FILE" ]]; then
        log_ok "Credentials already exist in $ENV_FILE; keeping them."
        ENV_ACTION="kept"
        return
    fi

    log_step "Writing instance-user credentials to $ENV_FILE..."
    mkdir -p "$(dirname "$ENV_FILE")"
    local pass
    pass="$(openssl rand -hex 16)"
    (
        umask 077
        printf 'INSTANCE_USER=%s\nINSTANCE_PASS=%s\n' "$INSTANCE_USER_DEFAULT" "$pass" > "$ENV_FILE"
        flip_settings >> "$ENV_FILE"
    )
    log_ok "Credentials are written."
    ENV_ACTION="generated"
}

# The variant's flip settings, commented out, so a camera mounted upside down
# is fixed in the file the Device already has rather than from the docs.
flip_settings() {
    local compose="$VARIANT_DIR/compose.yaml"
    if grep -q 'CAMERA_HFLIP' "$compose" 2>/dev/null; then
        printf '\n# Flip the picture: uncomment one or both, then start the Device again.\n'
        printf '# HFLIP mirrors it left to right, VFLIP turns it top to bottom, both turn it 180 degrees.\n'
        printf '#CAMERA_HFLIP=true\n#CAMERA_VFLIP=true\n'
    elif grep -q 'USB_CAMERA_FILTER' "$compose" 2>/dev/null; then
        printf '\n# Flip the picture: uncomment this, then start the Device again. hflip mirrors it\n'
        printf '# left to right, vflip turns it top to bottom, hflip,vflip turns it 180 degrees.\n'
        printf '#USB_CAMERA_FILTER=hflip,vflip\n'
    fi
}

# Read a KEY=value line back from the env file without sourcing it.
env_value() {
    sed -n "s/^$1=//p" "$ENV_FILE" | tail -n 1
}

# Set KEY=value in the env file: replace the line if present, else append.
# Rewritten with cat-over rather than mv, so the file keeps its 0600 mode.
set_env_value() {
    local key="$1" value="$2" tmp
    tmp="$(mktemp)"
    awk -v key="$key" -v value="$value" '
        index($0, key "=") == 1 { if (!done) print key "=" value; done = 1; next }
        { print }
        END { if (!done) print key "=" value }
    ' "$ENV_FILE" > "$tmp"
    cat "$tmp" > "$ENV_FILE"
    rm -f "$tmp"
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                        CAMERA
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
# A camera variant's compose.yaml maps the webcam named by USB_CAMERA into the
# container. Recording its stable by-id path here is what keeps "generate,
# then `docker compose up -d`" one command. /dev/videoN is never used: its
# numbering shifts between boots and replugs.

# Does this variant capture from a webcam? Its compose file says so.
needs_camera() {
    [[ -n "$CAMERA" ]] || grep -q 'USB_CAMERA' "$VARIANT_DIR/compose.yaml" 2>/dev/null
}

ensure_camera() {
    local current
    current="$(env_value USB_CAMERA)"

    if [[ -n "$CAMERA" ]]; then
        if [[ "$current" == "$CAMERA" ]]; then
            log_ok "USB_CAMERA is already $CAMERA."
            CAMERA_ACTION="kept"
        else
            set_env_value USB_CAMERA "$CAMERA"
            log_ok "USB_CAMERA is set to $CAMERA."
            CAMERA_ACTION="set"
        fi
        return
    fi

    if [[ -n "$current" ]]; then
        log_ok "Webcam already chosen in $ENV_FILE; keeping $current."
        CAMERA_ACTION="kept"
        return
    fi

    log_step "Looking for a webcam in $V4L_BY_ID_DIR..."
    # A UVC webcam's capture node is its -video-index0 entry; index1 carries
    # metadata only.
    local found=() candidate
    for candidate in "$V4L_BY_ID_DIR"/*-video-index0; do
        if [[ -c "$candidate" ]]; then
            found+=("$candidate")
        fi
    done

    if [[ ${#found[@]} -eq 1 ]]; then
        set_env_value USB_CAMERA "${found[0]}"
        log_ok "Found one webcam; USB_CAMERA is set to ${found[0]}."
        CAMERA_ACTION="set"
    elif [[ ${#found[@]} -eq 0 ]]; then
        log_warn "No webcam found in $V4L_BY_ID_DIR. Plug it in and re-run, or name it with --camera PATH."
        CAMERA_ACTION="missing"
    else
        log_warn "Found ${#found[@]} webcams and will not guess. Re-run with --camera PATH, one of:"
        for candidate in "${found[@]}"; do
            printf '         %s\n' "$candidate"
        done
        CAMERA_ACTION="missing"
    fi
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                   CSI DEVICES
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
# The CSI variant runs unprivileged, so Docker must be told which device
# nodes libcamera may open: the media controllers, the V4L2 video and
# sub-device nodes (sensor, ISP, and on a Pi 4 the hardware encoder) and the
# DMA heaps. Their numbers differ between a Pi 4 and a Pi 5, and the media
# major is allocated at boot, so no fixed list fits every Pi. The list is
# taken here, on the Device, into compose.override.yaml, which
# `docker compose` reads by itself. A node that later disappears stops
# `docker compose up` with its path in the error; re-running refreshes it.

OVERRIDE_MARKER="# Written by gen-cert.sh"

# Is this the Pi camera module variant? Its mediamtx.yml says so.
needs_csi_devices() {
    grep -q 'source: rpiCamera' "$VARIANT_DIR/mediamtx.yml" 2>/dev/null
}

# One node per line. Globs sort, so the same Pi always yields the same list.
csi_device_nodes() {
    local node
    for node in "$DEV_DIR"/media* "$DEV_DIR"/video* "$DEV_DIR"/v4l-subdev*; do
        if [[ -c "$node" ]]; then
            printf '%s\n' "$node"
        fi
    done
    # A directory: Docker adds every heap in it.
    if [[ -d "$DEV_DIR/dma_heap" ]]; then
        printf '%s\n' "$DEV_DIR/dma_heap"
    fi
    return 0
}

ensure_csi_devices() {
    local override="$VARIANT_DIR/compose.override.yaml"
    local nodes=() node content

    log_step "Looking for camera devices in $DEV_DIR..."
    while IFS= read -r node; do
        nodes+=("$node")
    done < <(csi_device_nodes)
    DEVICES_COUNT=${#nodes[@]}

    if [[ $DEVICES_COUNT -eq 0 ]]; then
        log_warn "No camera devices in $DEV_DIR. Run this on the Pi itself, with the camera connected."
        DEVICES_ACTION="missing"
        return
    fi

    if [[ -f "$override" ]] && ! head -n 1 "$override" | grep -qF "$OVERRIDE_MARKER"; then
        log_warn "$override was not written by this script, so it is left alone. List these under services.mediamtx.devices in it yourself:"
        for node in "${nodes[@]}"; do
            printf '         - %s\n' "$node"
        done
        DEVICES_ACTION="missing"
        return
    fi

    content="$OVERRIDE_MARKER: the camera device nodes on this Pi, which the
# CSI kit's unprivileged container may open. Re-run ../gen-cert.sh after a
# kernel or hardware change; edits here are overwritten.
services:
  mediamtx:
    devices:"
    for node in "${nodes[@]}"; do
        content+=$'\n'"      - $node"
    done

    if [[ -f "$override" && "$(cat "$override")" == "$content" ]]; then
        log_ok "Camera devices unchanged in $override; keeping it."
        DEVICES_ACTION="kept"
        return
    fi

    printf '%s\n' "$content" > "$override"
    log_ok "Listed $DEVICES_COUNT camera devices in $override."
    DEVICES_ACTION="set"
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                 GNSS RECEIVER
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
# Every variant can run the GPS Sidecar (`docker compose --profile gps`),
# which reads the receiver named by GPS_TTY. As with the webcam, its stable
# by-id path is recorded, never /dev/ttyACMn, whose numbers shift. GPS is
# optional, so finding no receiver is not a warning.

# Does this variant include the GPS Sidecar? Its compose file says so.
needs_gps() {
    grep -q 'gps/compose.yaml' "$VARIANT_DIR/compose.yaml" 2>/dev/null
}

# Is this by-id entry a GNSS receiver's NMEA port? A GPS puck says so in its
# name (u-blox, "GPS", "GNSS"). An LTE HAT's modem carries NMEA on interface
# 01 beside its diagnostic, AT and modem ports (Quectel EC25/EG25, SIMCom
# SIM7600). A plain USB-serial cable could be anything, so it is never taken.
is_gnss_port() {
    local name
    name="$(printf '%s' "${1##*/}" | tr 'A-Z' 'a-z')"
    case "$name" in
        *gps*|*gnss*|*u-blox*|*ublox*) return 0 ;;
        *quectel*-if01-port0|*simtech*-if01-port0) return 0 ;;
    esac
    return 1
}

ensure_gps() {
    local current
    current="$(env_value GPS_TTY)"
    if [[ -n "$current" ]]; then
        log_ok "GNSS receiver already chosen in $ENV_FILE; keeping $current."
        GPS_ACTION="kept"
        return
    fi

    log_step "Looking for a GNSS receiver in $SERIAL_BY_ID_DIR..."
    local found=() candidate
    for candidate in "$SERIAL_BY_ID_DIR"/*; do
        if [[ -c "$candidate" ]] && is_gnss_port "$candidate"; then
            found+=("$candidate")
        fi
    done

    if [[ ${#found[@]} -eq 1 ]]; then
        set_env_value GPS_TTY "${found[0]}"
        log_ok "Found one GNSS receiver; GPS_TTY is set to ${found[0]}."
        GPS_ACTION="set"
    elif [[ ${#found[@]} -eq 0 ]]; then
        log_info "No GNSS receiver found. GPS is optional; plug one in and re-run to use the GPS Sidecar."
    else
        log_warn "Found ${#found[@]} GNSS receivers and will not guess. Set GPS_TTY in $ENV_FILE to one of:"
        for candidate in "${found[@]}"; do
            printf '         %s\n' "$candidate"
        done
        GPS_ACTION="missing"
    fi
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                          MAIN
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
main() {
    parse_args "$@"
    banner "DEVICE KIT CERTIFICATE" "$VARIANT_DIR"
    check_for_root
    check_openssl

    log_phase "CERTIFICATE"
    ensure_certificate
    read_fingerprint

    log_phase "CREDENTIALS"
    ensure_env_file

    # Needs the env file, which ensure_env_file has just made sure of.
    if needs_camera; then
        log_phase "CAMERA"
        ensure_camera
    fi

    if needs_csi_devices; then
        log_phase "CAMERA DEVICES"
        ensure_csi_devices
    fi

    if needs_gps; then
        log_phase "GNSS RECEIVER"
        ensure_gps
    fi

    if [[ "$CERT_ACTION" == "kept" && "$ENV_ACTION" == "kept" && "$CAMERA_ACTION" != "set" && "$DEVICES_ACTION" != "set" && "$GPS_ACTION" != "set" ]]; then
        log_complete "NOTHING TO DO — CERTIFICATE AND CREDENTIALS ALREADY EXIST"
    else
        log_complete "DEVICE CERTIFICATE READY"
    fi
    log_info "Fingerprint:    $FINGERPRINT"
    log_info "Instance user:  $(env_value INSTANCE_USER)"
    log_info "Password:       $(env_value INSTANCE_PASS)"
    if [[ "$CAMERA_ACTION" == "set" || "$CAMERA_ACTION" == "kept" ]]; then
        log_info "Webcam:         $(env_value USB_CAMERA)"
    elif [[ "$CAMERA_ACTION" == "missing" ]]; then
        log_next "Choose the webcam first:  ./gen-cert.sh --camera /dev/v4l/by-id/<name>-video-index0 $VARIANT_DIR"
    fi
    if [[ "$DEVICES_ACTION" == "set" || "$DEVICES_ACTION" == "kept" ]]; then
        log_info "Camera devices: $DEVICES_COUNT, in $VARIANT_DIR/compose.override.yaml"
    elif [[ "$DEVICES_ACTION" == "missing" ]]; then
        log_next "List the camera devices first: connect the camera (Pi powered off), boot, and re-run this script on the Pi."
    fi
    if [[ "$GPS_ACTION" == "set" || "$GPS_ACTION" == "kept" ]]; then
        log_info "GNSS receiver:  $(env_value GPS_TTY)"
    elif [[ "$GPS_ACTION" == "missing" ]]; then
        log_next "Choose the GNSS receiver: set GPS_TTY=/dev/serial/by-id/<name> in $ENV_FILE"
    fi
    log_next "Start the Device:  cd $VARIANT_DIR && docker compose up -d"
    if [[ "$GPS_ACTION" == "set" || "$GPS_ACTION" == "kept" ]]; then
        log_next "Or with GPS:       cd $VARIANT_DIR && docker compose --profile gps up -d"
    fi
    log_next "Add it in Camera Viewer with the user and password above; confirm the fingerprint."
    echo
}

main "$@"
