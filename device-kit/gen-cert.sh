#!/usr/bin/env bash
#
# gen-cert.sh
#
# Generates a Device Kit Device's self-signed certificate (for RTSPS and the
# HTTPS API) and, if the Device has none yet, its instance-user credentials.
# For a variant that captures from a webcam (usb), it also records the
# webcam's stable /dev/v4l/by-id/ path in .env. For the Pi camera module
# variant (csi), it lists this Pi's camera device nodes in
# compose.override.yaml, so the container runs unprivileged. For the GPS
# Sidecar any variant can run, it records a GNSS receiver's stable
# /dev/serial/by-id/ path in .env. Prints the certificate
# fingerprint you confirm when adding the Device to Camera Viewer.
#
# Targets:
#   - Raspberry Pi OS / Debian / Ubuntu   (openssl from the base system)
#   - macOS                               (Homebrew or system openssl)
#
# Architecture: any (arm64, amd64, armv7l); needs bash and openssl only.
#
# Usage:  ./gen-cert.sh [options] [VARIANT_DIR]
#   VARIANT_DIR defaults to the current directory: the kit variant whose
#   compose.yaml will use the certificate (e.g. ./test-pattern).
# Do not run as root.
#
# The script is idempotent: an existing certificate or .env is kept and
# reported, never overwritten, unless --force asks for a new certificate.
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒

